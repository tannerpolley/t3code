/**
 * Fixed tracks, in rem, or in ch of the 12px row font where a track should follow the user's actual
 * font (as the title budget does).
 */
export const sidebarColumnLayout = {
  tracks: {
    usage: 2,
    caret: 0.75,
    location: 0.75,
    role: 0.75,
    provider: 1,
    // A model name of up to six characters, then its version, in fixed parts so versions align.
    model: { ch: 8 },
    effort: 2.5,
    name: 0,
    count: 1,
    time: 4.4375,
    work: 0.875,
  },
  gapPx: 3,
  /**
   * The model track's parts, with no gap between them: "Sonnet" at the 11px model size in
   * OpenDyslexic (5.28ch) plus a narrow space, then a version such as 8.8.
   */
  modelPartsCh: { name: 5.65, version: 2.35 },
  /** Optional columns in the order a narrowing sidebar drops them. */
  dropOrder: ["usage", "effort", "model"],
  rowPaddingRem: 1,
  titleCh: 10,
  titleFontRem: 0.75,
} as const;

export function generateSidebarColumnLayoutCss() {
  const { tracks, gapPx, titleFontRem, dropOrder, modelPartsCh } = sidebarColumnLayout;
  const entries = Object.entries(tracks);
  const visible = (hidden: ReadonlySet<string>) => entries.filter(([name]) => !hidden.has(name));
  const template = (hidden: ReadonlySet<string>) =>
    visible(hidden)
      .map(([name]) =>
        name === "name"
          ? "minmax(0, 1fr)"
          : name === "caret"
            ? // The caret starts at the inset, or after usage when that reaches further.
              "calc(var(--sidebar-caret-width) + max(0px, var(--sidebar-thread-inset, 0px) - var(--sidebar-thread-lead)))"
            : `var(--sidebar-${name}-width)`,
      )
      .join(" ");
  // The lead is the caret column's offset from the row start, past the usage column.
  const leadingTracks = entries.slice(
    0,
    entries.findIndex(([name]) => name === "caret"),
  );
  const lead = (hidden: ReadonlySet<string>) => {
    const shown = leadingTracks.filter(([name]) => !hidden.has(name));
    return shown.length === 0
      ? "0px"
      : `calc(${shown.map(([name]) => `var(--sidebar-${name}-width)`).join(" + ")} + ${shown.length * gapPx}px)`;
  };
  const threshold = (hidden: ReadonlySet<string>) => {
    const budget = sidebarColumnBudget(hidden);
    return `calc(${budget.rem}rem + ${budget.px}px + ${budget.ch}ch)`;
  };
  const full = new Set<string>();
  let css = `/* Generated by SidebarColumns.layout.ts; regenerate with the layout generator. */\n@utility sidebar-columns-container {\n  --sidebar-thread-lead: ${lead(full)};\n${entries
    .filter(([name]) => name !== "name")
    .map(
      ([name, width]) =>
        `  --sidebar-${name}-width: ${typeof width === "number" ? `${width}rem` : `${width.ch}ch`};`,
    )
    .join(
      "\n",
    )}\n  --sidebar-model-name-width: ${modelPartsCh.name}ch;\n  --sidebar-model-version-width: ${modelPartsCh.version}ch;\n  container: sidebar-columns / inline-size;\n  min-width: 0;\n  font-size: ${titleFontRem}rem;\n}\n@utility sidebar-thread-columns {\n  grid-template-columns: ${template(full)};\n  column-gap: ${gapPx}px;\n}\n`;
  const hidden = new Set<string>();
  for (const column of dropOrder) {
    const boundary = threshold(hidden);
    hidden.add(column);
    const leadRule = leadingTracks.some(([name]) => name === column)
      ? `  .sidebar-thread-columns, .sidebar-caret-toggle { --sidebar-thread-lead: ${lead(hidden)}; }\n`
      : "";
    css += `@container sidebar-columns (width < ${boundary}) {\n  .sidebar-thread-columns { grid-template-columns: ${template(hidden)}; }\n  .sidebar-thread-${column} { display: none; }\n${leadRule}}\n`;
  }
  return css;
}

export function sidebarColumnBudget(hidden: ReadonlySet<string>) {
  const { tracks, rowPaddingRem, gapPx, titleCh } = sidebarColumnLayout;
  const visible = Object.entries(tracks)
    .filter(([name]) => !hidden.has(name))
    .map(([, width]) => width);
  return {
    rem: visible.reduce<number>(
      (sum, width) => sum + (typeof width === "number" ? width : 0),
      rowPaddingRem,
    ),
    px: (visible.length - 1) * gapPx,
    ch: visible.reduce<number>(
      (sum, width) => sum + (typeof width === "number" ? 0 : width.ch),
      titleCh,
    ),
  };
}
