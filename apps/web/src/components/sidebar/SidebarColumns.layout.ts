/**
 * Fixed tracks, in rem, or in ch of the 12px row font where a track should follow the user's actual
 * font (as the title budget does).
 */
const titleCh = 11;
// Optional columns stay until the title would shrink below this; a role name such as
// "Orchestrator" truncates first, since its role icon and tooltip still name it.
const titleReserveCh = 6;
// With role icons, thread titles are empty, so it reserves enough for a short program
// name such as "node", which keeps icons from costing more than names.
const labelCh = 4;
const modelStepCh = 0.5;

export const sidebarColumnLayout = {
  tracks: {
    caret: 1.5,
    location: 0.75,
    role: 0.75,
    provider: 1,
    // "Sonnet 5.5" at the 11px model size in OpenDyslexic (7.98ch) plus a narrow space. A narrowing
    // sidebar shrinks it to `minCh`, truncating the label, before the column drops.
    model: { ch: 8.4, minCh: 4.5 },
    // The model cell spans this track: room for its 14px effort bars and a gap before the name.
    effort: 1.125,
    // A role name: "Orchestrator" is 10.625ch at 12px in OpenDyslexic Bold, plus a narrow space.
    // The name cell takes its text's width; spare width goes to the spacer so badges, time and
    // status stay right-aligned.
    name: { ch: titleCh },
    spacer: 0,
    badge: 2.25,
    time: 4.4375,
    work: 0.875,
  },
  gapPx: 2,
  /**
   * Optional columns in the order a narrowing sidebar drops them; a group drops together. Effort
   * reads as part of the model, so it goes with it. The badge slots go last, so a very narrow
   * sidebar still has room for its title, time and status.
   */
  dropOrder: [["model", "effort"], ["badge"]],
  rowPaddingRem: 1,
  titleCh,
  titleReserveCh,
  titleFontRem: 0.75,
} as const;

export function generateSidebarColumnLayoutCss() {
  const { tracks, gapPx, titleFontRem, dropOrder } = sidebarColumnLayout;
  const entries = Object.entries(tracks);
  // Named cells keep their positions when a hidden track and its following gap shrink to zero.
  const template = entries
    .map(([name], index) => {
      const width =
        name === "name"
          ? "minmax(0, var(--sidebar-name-track, max-content))"
          : name === "spacer"
            ? "minmax(0, 1fr)"
            : name === "model"
              ? "var(--sidebar-model-track, var(--sidebar-model-step, var(--sidebar-model-width)))"
              : `var(--sidebar-${name}-track, var(--sidebar-${name}-width))`;
      const gap =
        index === entries.length - 1
          ? ""
          : ` var(--sidebar-${name}-gap, var(--sidebar-column-gap))`;
      return `[${name}] ${width}${gap}`;
    })
    .join(" ");
  const threshold = (
    hidden: ReadonlySet<string>,
    roleDisplay: "name" | "icon",
    modelCh?: number,
  ) => {
    const budget = sidebarColumnBudget(hidden, roleDisplay, modelCh);
    return `calc(${budget.rem}rem + ${budget.px}px + ${budget.ch}ch)`;
  };
  // Registered lengths compute once, in the container's font. Unregistered, a ch width resolves in
  // each row's own font, so the smaller child rows got narrower model tracks and their columns drifted.
  const chWidths: Array<[string, number]> = [
    ...entries.flatMap(([name, width]) =>
      typeof width === "number" ? [] : [[`${name}-width`, width.ch] as [string, number]],
    ),
  ];
  let css = `/* Generated by SidebarColumns.layout.ts; regenerate with the layout generator. */\n${chWidths
    .map(
      ([name]) =>
        `@property --sidebar-${name} {\n  syntax: "<length>";\n  inherits: true;\n  initial-value: 0px;\n}\n`,
    )
    .join("")}@utility sidebar-columns-container {\n${entries
    .filter(([name, width]) => name !== "spacer" && typeof width === "number")
    .map(([name, width]) => `  --sidebar-${name}-width: ${width}rem;`)
    .concat(chWidths.map(([name, ch]) => `  --sidebar-${name}: ${ch}ch;`))
    .join(
      "\n",
    )}\n  --sidebar-column-gap: ${gapPx}px;\n  container: sidebar-columns / inline-size;\n  min-width: 0;\n  font-size: ${titleFontRem}rem;\n}\n@utility sidebar-thread-columns {\n  grid-template-columns: ${template};\n  column-gap: 0;\n}\n[data-sidebar-role-display="name"]:has(.sidebar-role-title) {\n  --sidebar-name-track: var(--sidebar-name-width);\n}\n`;
  // The model cell spans the effort track, so its effort bars follow the label.
  css += entries
    .map(
      ([name]) =>
        `.sidebar-thread-${name} { grid-column: ${name === "model" ? "model / name" : name}; }\n`,
    )
    .join("");
  for (const roleDisplay of ["name", "icon"] as const) {
    const hidden = new Set<string>();
    const container = roleDisplay === "name" ? "sidebar-columns-name" : "sidebar-columns";
    // The model narrows in half-character steps before its group drops. Named container queries
    // give every row in a list the same step; `cqw` would read a nested thread-row container.
    // The last step lands on `minCh`, the width the drop threshold budgets for.
    const modelWidthAt = (step: number) =>
      Math.max(tracks.model.minCh, +(tracks.model.ch - step * modelStepCh).toFixed(4));
    const steps = Math.ceil((tracks.model.ch - tracks.model.minCh) / modelStepCh);
    for (let step = 1; step <= steps; step++) {
      const ch = modelWidthAt(step);
      const boundary = threshold(hidden, roleDisplay, modelWidthAt(step - 1));
      const scale = +(ch / tracks.model.ch).toFixed(4);
      css += `@container ${container} (width < ${boundary}) {\n  .sidebar-thread-columns { --sidebar-model-step: calc(var(--sidebar-model-width) * ${scale}); }\n}\n`;
    }
    for (const group of dropOrder) {
      const boundary = threshold(hidden, roleDisplay);
      for (const column of group) hidden.add(column);
      const tracksOff = group
        .map((column) => `--sidebar-${column}-track: 0px; --sidebar-${column}-gap: 0px;`)
        .join(" ");
      const cells = group.map((column) => `.sidebar-thread-${column}`).join(", ");
      css += `@container ${container} (width < ${boundary}) {\n  .sidebar-thread-columns { ${tracksOff} }\n  ${cells} { display: none; }\n}\n`;
    }
  }
  return css;
}

/** A row's fixed width with the model at `modelCh` and the title at its reserve. */
export function sidebarColumnBudget(
  hidden: ReadonlySet<string>,
  roleDisplay: "name" | "icon" = "name",
  modelCh: number = sidebarColumnLayout.tracks.model.minCh,
) {
  const { tracks, rowPaddingRem, gapPx } = sidebarColumnLayout;
  const visible = Object.entries(tracks)
    .filter(([name]) => !hidden.has(name) && (name !== "role" || roleDisplay === "icon"))
    .map(([name, width]) =>
      name === "model"
        ? { ch: modelCh }
        : name === "name"
          ? { ch: roleDisplay === "icon" ? labelCh : titleReserveCh }
          : width,
    );
  return {
    rem: visible.reduce<number>(
      (sum, width) => sum + (typeof width === "number" ? width : 0),
      rowPaddingRem,
    ),
    px: (visible.length - 1) * gapPx,
    ch: visible.reduce<number>((sum, width) => sum + (typeof width === "number" ? 0 : width.ch), 0),
  };
}
