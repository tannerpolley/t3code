/** Fixed physical tracks, in rem; the title budget uses the user's actual font via ch. */
export const sidebarColumnLayout = {
  tracks: {
    caret: 0.75,
    location: 0.75,
    role: 0.75,
    provider: 1,
    model: 3,
    effort: 2.5,
    name: 0,
    count: 1,
    time: 2,
    work: 0.875,
    usage: 2,
  },
  gapPx: 4,
  rowPaddingRem: 1,
  indentRem: 0.75,
  titleCh: 10,
  titleFontRem: 0.75,
} as const;

export function generateSidebarColumnLayoutCss() {
  const { tracks, gapPx, indentRem, titleFontRem } = sidebarColumnLayout;
  const entries = Object.entries(tracks);
  const template = (hidden: ReadonlySet<string>) =>
    entries
      .filter(([name]) => !hidden.has(name))
      .map(([name]) => (name === "name" ? "minmax(0, 1fr)" : `var(--sidebar-${name}-width)`))
      .join(" ");
  const threshold = (hidden: ReadonlySet<string>) => {
    const budget = sidebarColumnBudget(hidden);
    return `calc(${budget.rem}rem + ${budget.px}px + ${budget.ch}ch)`;
  };
  const full = new Set<string>();
  let css = `/* Generated by SidebarColumns.layout.ts; regenerate with the layout generator. */\n@utility sidebar-columns-container {\n  --sidebar-thread-step: ${indentRem}rem;\n${entries
    .filter(([name]) => name !== "name")
    .map(([name, width]) => `  --sidebar-${name}-width: ${width}rem;`)
    .join(
      "\n",
    )}\n  container: sidebar-columns / inline-size;\n  min-width: 0;\n  font-size: ${titleFontRem}rem;\n}\n@utility sidebar-thread-columns {\n  grid-template-columns: ${template(full)};\n  column-gap: ${gapPx}px;\n}\n`;
  const hidden = new Set<string>();
  for (const column of ["usage", "effort", "model"]) {
    const boundary = threshold(hidden);
    hidden.add(column);
    css += `@container sidebar-columns (width < ${boundary}) {\n  .sidebar-thread-columns { grid-template-columns: ${template(hidden)}; }\n  .sidebar-thread-${column} { display: none; }\n}\n`;
  }
  return css;
}

export function sidebarColumnBudget(hidden: ReadonlySet<string>) {
  const { tracks, rowPaddingRem, gapPx, titleCh } = sidebarColumnLayout;
  const visible = Object.entries(tracks).filter(([name]) => !hidden.has(name));
  return {
    rem: visible.reduce<number>((sum, [, width]) => sum + width, rowPaddingRem),
    px: (visible.length - 1) * gapPx,
    ch: titleCh,
  };
}
