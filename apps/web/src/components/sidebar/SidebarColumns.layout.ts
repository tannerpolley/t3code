/**
 * Fixed tracks, in rem, or in ch of the 12px row font where a track should follow the user's actual
 * font (as the title budget does).
 */
const titleCh = 11;
// With role icons, thread titles are empty, but command and process labels still need this much.
const labelCh = 10;

export const sidebarColumnLayout = {
  tracks: {
    caret: 0.75,
    location: 0.75,
    role: 0.75,
    provider: 1,
    // "Sonnet" at the 11px model size in OpenDyslexic (5.28ch) plus a narrow space, then its own
    // column for the version, such as 8.8, so versions align.
    model: { ch: 5.65 },
    version: { ch: 2.35 },
    effort: 2.5,
    // A role-name title: "Orchestrator" is 10.625ch at 12px in OpenDyslexic Bold, plus a narrow
    // space. Other titles take their text's width. Spare width goes to the spacer so counts,
    // badges, time and status stay right-aligned.
    name: { ch: titleCh },
    spacer: 0,
    // A collapsed row's hidden work count, right-aligned just before the badges.
    count: 1,
    // Every row reserves both badge slots, so issue and pull request icons line up whichever it has:
    // each fits its icon and three digits (an orchestrator can hold 100+ pull requests).
    issue: 2.25,
    pr: 2.25,
    time: 4.4375,
    work: 0.875,
  },
  gapPx: 3,
  /**
   * Optional columns in the order a narrowing sidebar drops them; a group drops together. The badge
   * slots go last, so a very narrow sidebar still has room for its title, time and status.
   */
  dropOrder: [["effort"], ["model", "version"], ["issue", "pr"]],
  rowPaddingRem: 1,
  titleCh,
  titleFontRem: 0.75,
} as const;

export function generateSidebarColumnLayoutCss() {
  const { tracks, gapPx, titleFontRem, dropOrder } = sidebarColumnLayout;
  const entries = Object.entries(tracks);
  // Named cells keep their positions when a hidden track and its following gap shrink to zero.
  const template = entries
    .map(([name], index) => {
      const width =
        name === "name"
          ? "minmax(0, var(--sidebar-name-track, max-content))"
          : name === "spacer"
            ? "minmax(0, 1fr)"
            : `var(--sidebar-${name}-track, var(--sidebar-${name}-width))`;
      const gap =
        index === entries.length - 1
          ? ""
          : ` var(--sidebar-${name}-gap, var(--sidebar-column-gap))`;
      return `[${name}] ${width}${gap}`;
    })
    .join(" ");
  const threshold = (hidden: ReadonlySet<string>, roleDisplay: "name" | "icon") => {
    const budget = sidebarColumnBudget(hidden, roleDisplay);
    return `calc(${budget.rem}rem + ${budget.px}px + ${budget.ch}ch)`;
  };
  // Registered lengths compute once, in the container's font. Unregistered, a ch width resolves in
  // each row's own font, so the smaller child rows got narrower model tracks and their columns drifted.
  const chWidths = entries.flatMap(([name, width]) => (typeof width === "number" ? [] : [name]));
  let css = `/* Generated by SidebarColumns.layout.ts; regenerate with the layout generator. */\n${chWidths
    .map(
      (name) =>
        `@property --sidebar-${name}-width {\n  syntax: "<length>";\n  inherits: true;\n  initial-value: 0px;\n}\n`,
    )
    .join("")}@utility sidebar-columns-container {\n${entries
    .filter(([name]) => name !== "spacer")
    .map(
      ([name, width]) =>
        `  --sidebar-${name}-width: ${typeof width === "number" ? `${width}rem` : `${width.ch}ch`};`,
    )
    .join(
      "\n",
    )}\n  --sidebar-column-gap: ${gapPx}px;\n  container: sidebar-columns / inline-size;\n  min-width: 0;\n  font-size: ${titleFontRem}rem;\n}\n@utility sidebar-thread-columns {\n  grid-template-columns: ${template};\n  column-gap: 0;\n}\n[data-sidebar-role-display="name"]:has(.sidebar-role-title) {\n  --sidebar-name-track: var(--sidebar-name-width);\n}\n`;
  css += entries.map(([name]) => `.sidebar-thread-${name} { grid-column: ${name}; }\n`).join("");
  for (const roleDisplay of ["name", "icon"] as const) {
    const hidden = new Set<string>();
    const container = roleDisplay === "name" ? "sidebar-columns-name" : "sidebar-columns";
    for (const group of dropOrder) {
      const boundary = threshold(hidden, roleDisplay);
      for (const column of group) hidden.add(column);
      const tracksOff = group
        .map((column) => `--sidebar-${column}-track: 0px; --sidebar-${column}-gap: 0px;`)
        .join(" ");
      const cells = group.map((column) => `.sidebar-thread-${column}`).join(", ");
      css += `@container ${container} (width < ${boundary}) {\n  .sidebar-thread-columns { ${tracksOff} }\n  ${cells} { display: none; }\n}\n`;
    }
  }
  return css;
}

export function sidebarColumnBudget(
  hidden: ReadonlySet<string>,
  roleDisplay: "name" | "icon" = "name",
) {
  const { tracks, rowPaddingRem, gapPx } = sidebarColumnLayout;
  const visible = Object.entries(tracks)
    .filter(([name]) => !hidden.has(name) && (name !== "role" || roleDisplay === "icon"))
    .map(([name, width]) => (name === "name" && roleDisplay === "icon" ? { ch: labelCh } : width));
  return {
    rem: visible.reduce<number>(
      (sum, width) => sum + (typeof width === "number" ? width : 0),
      rowPaddingRem,
    ),
    px: (visible.length - 1) * gapPx,
    ch: visible.reduce<number>((sum, width) => sum + (typeof width === "number" ? 0 : width.ch), 0),
  };
}
