it.live("an agent reloads its tab in place, bypassing the cache when asked", () =>
  Effect.scoped(
    Effect.gen(function* () {
      const { broker, tabId } = yield* ready;
      const page = contexts[0]!.page;
      const session = contexts[0]!.sessions[0]!;
      const reload = (mode: "normal" | "bypassCache") =>
        broker.invoke({
          scope,
          tabId,
          operation: "navigate",
          input: { reload: mode, readiness: "none" },
        });
      yield* reload("normal");
      expect(page.reload).toHaveBeenCalledWith(expect.objectContaining({ waitUntil: "commit" }));
      yield* reload("bypassCache");
      expect(session.send).toHaveBeenCalledWith("Page.reload", { ignoreCache: true });
    }),
  ).pipe(Effect.provide(layer)),
);
